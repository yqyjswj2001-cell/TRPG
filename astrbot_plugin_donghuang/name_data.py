def _pick_tier(identity_tier):
    """身份阶层 → 名字档次"""
    if identity_tier in ("宗门杂役/普通人家子弟",):
        return "low"
    if identity_tier in ("外门弟子", "散修"):
        return "low" if random.random() < 0.3 else "mid"
    if identity_tier in ("内门弟子", "没落世家子弟"):
        return "mid"
    if identity_tier in ("内门天才",):
        return "high"
    if identity_tier in ("绝世妖孽",):
        return "top" if random.random() < 0.5 else "high"
    return "mid"

def _gen_name(gender, identity_tier=None, exclude=None, seed=None):
    """生成一个与身份匹配的名字。
    gender: '男' or '女'
    identity_tier: 阶层定位，决定名字档次
    exclude: 要排除的名字集合
    """
    rng = random.Random(seed) if seed is not None else random
    exclude = exclude or set()
    tier = _pick_tier(identity_tier)
    pool = _FEMALE_GIVEN if gender == "女" else _MALE_GIVEN
    a = pool[tier]["a"]
    b = pool[tier]["b"]

    for _ in range(200):
        surname = _pick_surname()
        if b:  # 双字名
            given = rng.choice(a) + rng.choice(b)
        else:  # a 已经是双字名
            given = rng.choice(a)
        full = surname + given
        if full not in exclude and len(full) <= 4:  # 复姓+双字名可能超长
            return full

    return _pick_surname() + rng.choice(a) + (rng.choice(b) if b else "")


# ===== 兼容旧接口 =====
def _gen_names(gender, count, identity_tier=None, exclude=None):
    exclude = set(exclude or [])
    names = []
    for _ in range(count):
        name = _gen_name(gender, identity_tier=identity_tier, exclude=exclude)
        exclude.add(name)
        names.append(name)
    return names

