"""
核心规则"铁律测试"
==================
东荒的立身之本是"代码管事实"。这份文件就是给这些事实上锁:
每写一条测试,就等于立下一条永远不许被打破的铁律。
以后不管你(或帮你写代码的 AI)怎么改代码,只要哪条铁律
被破坏,守门员就会亮红叉当场拦下。

新手用法:
  1. 先什么都不改,直接用——里面有一条永远通过的"环境自检",
     保证你第一次运行就能看到绿灯,先建立信心。
  2. 之后每周挑 1~2 条下面的示例,把 TODO 处改成你项目里
     真实的函数名,再删掉每行开头的 # 号,铁律就生效了。

小知识:所有名字以 test_ 开头的函数都会被 pytest 自动当作
测试来运行;函数里的 assert 意思是"我断言这件事必须成立,
否则本次检查算失败"。
"""

